import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const output = 'docs/COMPONENT_INDEX.md';

export function eligibleModulePath(path) {
  if (!/^(src\/components\/.+|src\/pages\/.+|src\/App\.tsx|src\/lib\/protectedRoutes\.ts)$/.test(path)) return false;
  if (!/\.tsx?$/.test(path) || /(?:\.d|\.test|\.spec)\.tsx?$/.test(path)) return false;
  return !path.split('/').some((segment) => segment.startsWith('.'));
}

export function listSourceModules(root = projectRoot) {
  const paths = [];
  function walk(directory) {
    if (!existsSync(directory)) return;
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (entry.name.startsWith('.') || entry.isSymbolicLink()) continue;
      const file = join(directory, entry.name);
      if (entry.isDirectory()) walk(file);
      else if (entry.isFile()) {
        const path = relative(root, file).split(sep).join('/');
        if (eligibleModulePath(path)) paths.push(path);
      }
    }
  }
  walk(resolve(root, 'src/components'));
  walk(resolve(root, 'src/pages'));
  for (const path of ['src/App.tsx', 'src/lib/protectedRoutes.ts']) {
    const absolute = resolve(root, path);
    if (existsSync(absolute) && statSync(absolute).isFile()) paths.push(path);
  }
  return paths.sort();
}

function escapeMarkdown(value) {
  return value.replace(/\r/g, '\\r').replace(/\n/g, '\\n')
    .replace(/\\/g, '\\\\').replace(/\|/g, '\\|')
    .replace(/\[/g, '\\[').replace(/\]/g, '\\]')
    .replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function encodedLink(path) {
  return path.split('/').map((part) => encodeURIComponent(part).replace(/[!'()*]/g,
    (char) => '%' + char.charCodeAt(0).toString(16).toUpperCase())).join('/');
}

function groupFor(path) {
  if (path.startsWith('src/components/')) return dirname(path).replace(/^src\//, '');
  return path.startsWith('src/pages/') ? 'pages' : 'route entrypoints';
}

export function renderComponentIndex(paths) {
  const groups = new Map();
  for (const path of [...new Set(paths)].sort()) {
    if (!eligibleModulePath(path)) throw new Error('Not an eligible source module: ' + path);
    const group = groupFor(path);
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push(path);
  }
  const lines = [
    '# Component and page module index', '',
    'Generated by `node scripts/generate-repo-index.mjs --write`. Check freshness with `--check`.',
    'These are **source modules**, not a React render tree, ownership graph, or proof of runtime imports.',
    'Helpers are intentionally included. Verify current source at the target Git SHA before editing.',
    'For natural-language entry points use [repository map](REPO_MAP.md); for policy use [docs index](README.md).',
    ''
  ];
  for (const group of [...groups.keys()].sort()) {
    lines.push('## ' + escapeMarkdown(group), '', '| Module | Source |', '|---|---|');
    for (const path of groups.get(group)) {
      const name = basename(path).replace(/\.tsx?$/, '');
      lines.push('| ' + escapeMarkdown(name) + ' | [' + escapeMarkdown(path) + '](../' + encodedLink(path) + ') |');
    }
    lines.push('');
  }
  return lines.join('\n') + '\n';
}

export function expectedComponentIndex(root = projectRoot) {
  return renderComponentIndex(listSourceModules(root));
}

export function checkComponentIndex(root = projectRoot) {
  const file = resolve(root, output);
  if (!existsSync(file)) return [output + ' missing; run node scripts/generate-repo-index.mjs --write'];
  return readFileSync(file, 'utf8') === expectedComponentIndex(root) ? [] :
    [output + ' is stale; run node scripts/generate-repo-index.mjs --write'];
}

export function writeComponentIndex(root = projectRoot) {
  const file = resolve(root, output);
  writeFileSync(file, expectedComponentIndex(root), 'utf8');
}
