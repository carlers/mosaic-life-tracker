const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const FUNCTION_DIR = resolve(ROOT, 'appwrite-functions');
const DEPLOY_POLL_MS = 1_000;
const DEPLOY_POLL_LIMIT = 180;

function flagValue(argv, name) {
  const index = argv.indexOf(name);
  if (index === -1) return '';
  return argv[index + 1] || '';
}

function repeatedValues(argv, name) {
  const values = [];
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === name && argv[index + 1]) values.push(argv[index + 1]);
  }
  return values;
}

function hasFlag(argv, name) {
  return argv.includes(name);
}

function normalizeEndpoint(value) {
  const raw = String(value || '').trim().replace(/\/+$/, '');
  if (!raw) return '';
  const url = new URL(raw);
  if (url.protocol !== 'https:' && url.hostname !== 'localhost') {
    throw new Error('Appwrite endpoint must use HTTPS unless it is localhost');
  }
  return raw.endsWith('/v1') ? raw : `${raw}/v1`;
}

function normalizeHostname(value) {
  const raw = String(value || '').trim();
  if (!raw) return '';
  const hostname = raw
    .replace(/^https?:\/\//i, '')
    .replace(/\/.*$/, '')
    .replace(/:\d+$/, '');
  if (!hostname || /\s/.test(hostname)) {
    throw new Error(`Invalid web hostname: ${raw}`);
  }
  return hostname;
}

export function parseBootstrapArgs(argv = [], env = process.env) {
  const endpoint = normalizeEndpoint(
    flagValue(argv, '--endpoint') || env.APPWRITE_ENDPOINT || ''
  );
  const projectId =
    flagValue(argv, '--project') || env.APPWRITE_PROJECT_ID || '';
  const apiKey = env.APPWRITE_API_KEY || '';
  const withDr = hasFlag(argv, '--with-dr');
  const platformOnly = hasFlag(argv, '--platform-only');
  const writeEnv = !hasFlag(argv, '--no-env-file');
  const overwriteEnv = hasFlag(argv, '--overwrite-env');
  const envFile =
    flagValue(argv, '--env-file') || env.MOSAIC_ENV_FILE || '.env.local';
  const messageFunctionId =
    flagValue(argv, '--message-function-id') ||
    env.MOSAIC_MESSAGE_ACTION_FUNCTION_ID ||
    'message_action';
  const drFunctionId =
    flagValue(argv, '--dr-function-id') ||
    env.MOSAIC_DR_FUNCTION_ID ||
    'dr_backup';
  const requestedHostnames = repeatedValues(argv, '--web-hostname');
  const webHostnames = [
    ...new Set(
      (requestedHostnames.length ? requestedHostnames : ['localhost'])
        .map(normalizeHostname)
        .filter(Boolean)
    ),
  ];

  if (!projectId) {
    throw new Error(
      'Missing Appwrite project ID. Pass --project <id> or set APPWRITE_PROJECT_ID.'
    );
  }
  if (!apiKey) {
    throw new Error(
      'Missing APPWRITE_API_KEY. Create a temporary project API key for provisioning.'
    );
  }
  if (!endpoint) {
    throw new Error(
      'Missing Appwrite endpoint. Pass --endpoint <url> or set APPWRITE_ENDPOINT.'
    );
  }
  if (!/^[a-zA-Z0-9][a-zA-Z0-9._-]{0,35}$/.test(messageFunctionId)) {
    throw new Error('Invalid message Function ID');
  }
  if (!/^[a-zA-Z0-9][a-zA-Z0-9._-]{0,35}$/.test(drFunctionId)) {
    throw new Error('Invalid DR Function ID');
  }
  if (messageFunctionId === drFunctionId) {
    throw new Error('Message and DR Function IDs must be different');
  }

  const drSecrets = {};
  const drVariables = {};
  if (withDr) {
    for (const name of [
      'R2_ACCOUNT_ID',
      'R2_ACCESS_KEY_ID',
      'R2_SECRET_ACCESS_KEY',
      'R2_BUCKET',
      'DR_ENCRYPTION_KEY_B64',
    ]) {
      if (!env[name]) {
        throw new Error(
          `--with-dr requires ${name}. Keep recovery secrets out of source control.`
        );
      }
      drSecrets[name] = env[name];
    }
    if (env.R2_ENDPOINT) drVariables.R2_ENDPOINT = env.R2_ENDPOINT;
  }

  return {
    endpoint,
    projectId,
    apiKey,
    withDr,
    platformOnly,
    writeEnv,
    overwriteEnv,
    envFile,
    messageFunctionId,
    drFunctionId,
    webHostnames,
    drSecrets,
    drVariables,
  };
}

export function renderBrowserEnv({
  endpoint,
  projectId,
  messageFunctionId = 'message_action',
}) {
  const t = MOSAIC_BROWSER_ENV.tables;
  return [
    '# Generated by npm run mosaic:bootstrap',
    `VITE_APPWRITE_ENDPOINT=${endpoint}`,
    `VITE_APPWRITE_PROJECT_ID=${projectId}`,
    `VITE_APPWRITE_DATABASE_ID=${MOSAIC_BROWSER_ENV.databaseId}`,
    `VITE_APPWRITE_STORAGE_BUCKET_ID=${MOSAIC_BROWSER_ENV.bucketId}`,
    `VITE_APPWRITE_MESSAGE_ACTION_FUNCTION_ID=${messageFunctionId}`,
    '',
    `VITE_APPWRITE_TABLE_TASKS=${t.tasks}`,
    `VITE_APPWRITE_TABLE_CATEGORIES=${t.categories}`,
    `VITE_APPWRITE_TABLE_DIARY=${t.diary}`,
    `VITE_APPWRITE_TABLE_SETTINGS=${t.settings}`,
    `VITE_APPWRITE_TABLE_FRIENDSHIPS=${t.friendships}`,
    `VITE_APPWRITE_TABLE_PROFILES=${t.profiles}`,
    `VITE_APPWRITE_TABLE_MESSAGES=${t.messages}`,
    '',
  ].join('\n');
}

export async function writeBrowserEnvFile(
  config,
  {
    fileExists = async (path) => {
      try {
        await readFile(path);
        return true;
      } catch (error) {
        if (error?.code === 'ENOENT') return false;
        throw error;
      }
    },
    write = writeFile,
  } = {}
) {
  const path = resolve(ROOT, config.envFile);
  if ((await fileExists(path)) && !config.overwriteEnv) {
    throw new Error(
      `${relative(ROOT, path)} already exists. Use --overwrite-env to replace it.`
    );
  }
  await write(
    path,
    renderBrowserEnv(config),
    { encoding: 'utf8', mode: 0o600 }
  );
  return path;
}

export function createBootstrapServices({ endpoint, projectId, apiKey }) {
  const client = new Client()
    .setEndpoint(endpoint)
    .setProject(projectId)
    .setKey(apiKey);
  return {
    tablesDB: new TablesDB(client),
    storage: new Storage(client),
    functions: new Functions(client),
    users: new Users(client),
    project: new Project(client),
  };
}

function listCount(result, key) {
  const values = Array.isArray(result?.[key]) ? result[key] : [];
  return { count: values.length, ids: values.map((item) => item.$id).filter(Boolean) };
}

export async function inspectTarget(services) {
  const query = [Query.limit(100)];
  const [databases, buckets, functions, users] = await Promise.all([
    services.tablesDB.list({ queries: query, total: false }),
    services.storage.listBuckets({ queries: query, total: false }),
    services.functions.list({ queries: query, total: false }),
    services.users.list({ queries: query, total: false }),
  ]);
  return {
    databases: listCount(databases, 'databases'),
    buckets: listCount(buckets, 'buckets'),
    functions: listCount(functions, 'functions'),
    users: listCount(users, 'users'),
  };
}

export async function assertEmptyTarget(services) {
  const state = await inspectTarget(services);
  const occupied = Object.entries(state)
    .filter(([, value]) => value.count > 0)
    .map(([key, value]) => `${key}=${value.ids.join(',') || value.count}`);
  if (occupied.length) {
    throw new Error(
      `Refusing to bootstrap a non-empty Appwrite project (${occupied.join(
        '; '
      )}). Use a fresh project so Mosaic never overwrites unrelated data.`
    );
  }
  return state;
}

function platformId(hostname) {
  return `mosaic_${createHash('sha256')
    .update(hostname)
    .digest('hex')
    .slice(0, 20)}`;
}

export async function ensureWebPlatforms(project, hostnames) {
  const existing = await project.listPlatforms({ queries: [], total: false });
  const platforms = Array.isArray(existing?.platforms) ? existing.platforms : [];
  const existingHosts = new Set(
    platforms
      .filter((item) => item.type === 'web' && item.hostname)
      .map((item) => item.hostname)
  );
  const created = [];
  for (const hostname of hostnames) {
    if (existingHosts.has(hostname)) continue;
    await project.createWebPlatform({
      platformId: platformId(hostname),
      name: hostname === 'localhost' ? 'Mosaic Local' : `Mosaic ${hostname}`,
      hostname,
    });
    created.push(hostname);
  }
  return created;
}

function writeAscii(buffer, offset, length, value) {
  const bytes = Buffer.from(String(value), 'utf8');
  bytes.copy(buffer, offset, 0, Math.min(bytes.length, length));
}

function octal(value, width) {
  return Math.floor(value).toString(8).padStart(width - 1, '0') + '\0';
}

function tarHeader(name, size) {
  const header = Buffer.alloc(512);
  writeAscii(header, 0, 100, name);
  writeAscii(header, 100, 8, octal(0o644, 8));
  writeAscii(header, 108, 8, octal(0, 8));
  writeAscii(header, 116, 8, octal(0, 8));
  writeAscii(header, 124, 12, octal(size, 12));
  writeAscii(header, 136, 12, octal(0, 12));
  header.fill(0x20, 148, 156);
  header[156] = '0'.charCodeAt(0);
  writeAscii(header, 257, 6, 'ustar\0');
  writeAscii(header, 263, 2, '00');
  let checksum = 0;
  for (const byte of header) checksum += byte;
  writeAscii(
    header,
    148,
    8,
    checksum.toString(8).padStart(6, '0') + '\0 '
  );
  return header;
}

async function listSourceFiles(root, current = root) {
  const found = [];
  const entries = await readdir(current, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name === 'node_modules' || entry.name === '.tmp') continue;
    const path = join(current, entry.name);
    if (entry.isDirectory()) {
      found.push(...(await listSourceFiles(root, path)));
    } else if (entry.isFile()) {
      found.push({
        path,
        name: relative(root, path).replaceAll('\\', '/'),
      });
    }
  }
  return found.sort((a, b) => a.name.localeCompare(b.name));
}

export async function packageFunctionDirectory(directory) {
  const files = await listSourceFiles(directory);
  if (!files.length) throw new Error(`Function source directory is empty: ${directory}`);
  const chunks = [];
  for (const file of files) {
    const body = await readFile(file.path);
    if (Buffer.byteLength(file.name) > 100) {
      throw new Error(`Function source path is too long for bootstrap tar: ${file.name}`);
    }
    chunks.push(tarHeader(file.name, body.length), body);
    const padding = (512 - (body.length % 512)) % 512;
    if (padding) chunks.push(Buffer.alloc(padding));
  }
  chunks.push(Buffer.alloc(1024));
  return gzipSync(Buffer.concat(chunks), { level: 9 });
}

async function readFunctionConfig(directory) {
  return JSON.parse(
    await readFile(join(directory, 'function.config.json'), 'utf8')
  );
}

function functionCreateInput(config, functionId, overrides = {}) {
  return {
    functionId,
    name: config.name,
    runtime: config.runtime,
    execute: config.execute || [],
    events: config.events || [],
    schedule:
      overrides.schedule !== undefined
        ? overrides.schedule
        : config.schedule || '',
    timeout: config.timeout,
    enabled: true,
    logging: true,
    entrypoint: config.entrypoint,
    commands: config.commands,
    scopes: config.scopes || [],
    deploymentRetention: config.deploymentRetention ?? 0,
  };
}

function variableId(key) {
  return `v_${key.toLowerCase()}`.slice(0, 36);
}

async function createVariables(functions, functionId, variables, secretKeys = []) {
  const secretSet = new Set(secretKeys);
  for (const [key, value] of Object.entries(variables)) {
    await functions.createVariable({
      functionId,
      variableId: variableId(key),
      key,
      value: String(value),
      secret: secretSet.has(key),
    });
  }
}

async function deployFunction(
  functions,
  functionId,
  sourceDirectory,
  config,
  { sleep = (ms) => new Promise((resolvePromise) => setTimeout(resolvePromise, ms)) } = {}
) {
  const archive = await packageFunctionDirectory(sourceDirectory);
  const deployment = await functions.createDeployment({
    functionId,
    code: InputFile.fromBuffer(
      archive,
      `${functionId}.tar.gz`,
      'application/gzip'
    ),
    activate: true,
    entrypoint: config.entrypoint,
    commands: config.commands,
  });

  for (let attempt = 0; attempt < DEPLOY_POLL_LIMIT; attempt += 1) {
    const current = await functions.getDeployment({
      functionId,
      deploymentId: deployment.$id,
    });
    if (current.status === 'ready') return current;
    if (current.status === 'failed' || current.status === 'canceled') {
      throw new Error(
        `Function ${functionId} deployment ${current.status}: ${current.buildLogs || ''}`
      );
    }
    await sleep(DEPLOY_POLL_MS);
  }
  throw new Error(`Function ${functionId} deployment did not become ready`);
}

async function provisionFunction({
  functions,
  directory,
  functionId,
  extraVariables = {},
  secretVariables = {},
  functionOverrides = {},
  sleep,
}) {
  const config = await readFunctionConfig(directory);
  await functions.create(
    functionCreateInput(config, functionId, functionOverrides)
  );
  await createVariables(functions, functionId, {
    ...(config.nonSecretVariables || {}),
    ...extraVariables,
  });
  await createVariables(
    functions,
    functionId,
    secretVariables,
    Object.keys(secretVariables)
  );
  return deployFunction(functions, functionId, directory, config, { sleep });
}

export async function deployRecoveredProjectFunctions(
  {
    endpoint,
    projectId,
    apiKey,
    messageFunctionId,
    drFunctionId,
  },
  {
    services = createBootstrapServices({ endpoint, projectId, apiKey }),
    sleep,
    log = () => {},
  } = {}
) {
  const listed = await services.functions.list({
    queries: [Query.limit(100)],
    total: false,
  });
  const existing = Array.isArray(listed?.functions) ? listed.functions : [];
  if (existing.length > 0) {
    throw new Error(
      `Refusing to deploy recovery Functions because target already has Functions: ${existing
        .map((item) => item.$id)
        .filter(Boolean)
        .join(', ') || existing.length}`
    );
  }

  const messageConfig = await readFunctionConfig(
    join(FUNCTION_DIR, 'message-action')
  );
  const drConfig = await readFunctionConfig(join(FUNCTION_DIR, 'dr-backup'));
  const resolvedMessageFunctionId =
    messageFunctionId || messageConfig.$id || 'message_action';
  const resolvedDrFunctionId = drFunctionId || drConfig.$id || 'dr_backup';

  if (resolvedMessageFunctionId === resolvedDrFunctionId) {
    throw new Error('Message and DR Function IDs must be different');
  }

  log('Deploying schedule-disabled message-action Function...');
  await provisionFunction({
    functions: services.functions,
    directory: join(FUNCTION_DIR, 'message-action'),
    functionId: resolvedMessageFunctionId,
    extraVariables: { APPWRITE_DATABASE_ID: MOSAIC_DATABASE.id },
    functionOverrides: { schedule: '' },
    sleep,
  });

  log('Deploying schedule-disabled dr-backup Function...');
  await provisionFunction({
    functions: services.functions,
    directory: join(FUNCTION_DIR, 'dr-backup'),
    functionId: resolvedDrFunctionId,
    functionOverrides: { schedule: '' },
    sleep,
  });

  const [messageFunction, drFunction] = await Promise.all([
    services.functions.get({ functionId: resolvedMessageFunctionId }),
    services.functions.get({ functionId: resolvedDrFunctionId }),
  ]);
  if (messageFunction.schedule || drFunction.schedule) {
    throw new Error('Recovery Function schedules must remain disabled');
  }

  return {
    messageFunctionId: resolvedMessageFunctionId,
    drFunctionId: resolvedDrFunctionId,
  };
}

export async function bootstrapMosaicProject(
  config,
  {
    services = createBootstrapServices(config),
    sleep,
    log = () => {},
  } = {}
) {
  if (config.platformOnly) {
    const platforms = await ensureWebPlatforms(
      services.project,
      config.webHostnames
    );
    return { platformOnly: true, platforms };
  }

  await assertEmptyTarget(services);

  log('Creating Mosaic database...');
  await services.tablesDB.create({
    databaseId: MOSAIC_DATABASE.id,
    name: MOSAIC_DATABASE.name,
    enabled: MOSAIC_DATABASE.enabled,
  });

  for (const table of MOSAIC_TABLES) {
    log(`Creating table ${table.id}...`);
    await services.tablesDB.createTable({
      databaseId: MOSAIC_DATABASE.id,
      tableId: table.id,
      name: table.name,
      permissions: table.permissions,
      rowSecurity: table.rowSecurity,
      enabled: table.enabled,
      columns: table.columns,
      indexes: table.indexes,
    });
  }

  log('Creating image bucket...');
  await services.storage.createBucket({
    bucketId: MOSAIC_BUCKET.id,
    name: MOSAIC_BUCKET.name,
    permissions: MOSAIC_BUCKET.permissions,
    fileSecurity: MOSAIC_BUCKET.fileSecurity,
    enabled: MOSAIC_BUCKET.enabled,
    maximumFileSize: MOSAIC_BUCKET.maximumFileSize,
    allowedFileExtensions: MOSAIC_BUCKET.allowedFileExtensions,
    compression: MOSAIC_BUCKET.compression,
    encryption: MOSAIC_BUCKET.encryption,
    antivirus: MOSAIC_BUCKET.antivirus,
    transformations: MOSAIC_BUCKET.transformations,
  });

  log('Deploying message-action Function...');
  await provisionFunction({
    functions: services.functions,
    directory: join(FUNCTION_DIR, 'message-action'),
    functionId: config.messageFunctionId,
    extraVariables: { APPWRITE_DATABASE_ID: MOSAIC_DATABASE.id },
    sleep,
  });

  if (config.withDr) {
    log('Deploying schedule-disabled disaster recovery Function...');
    await provisionFunction({
      functions: services.functions,
      directory: join(FUNCTION_DIR, 'dr-backup'),
      functionId: config.drFunctionId,
      extraVariables: config.drVariables,
      secretVariables: config.drSecrets,
      sleep,
    });
  }

  const platforms = await ensureWebPlatforms(
    services.project,
    config.webHostnames
  );

  return {
    platformOnly: false,
    databaseId: MOSAIC_DATABASE.id,
    tableIds: MOSAIC_TABLES.map((table) => table.id),
    bucketId: MOSAIC_BUCKET.id,
    messageFunctionId: config.messageFunctionId,
    drFunctionId: config.withDr ? config.drFunctionId : null,
    platforms,
  };
}
